import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

/**
 * Takes a snapshot of what the catalogue claims today, and commits it.
 *
 * The history lives in the repository rather than in a service, so `/changes` is built from files
 * anybody can read and the build can check. A catalogue change with no snapshot fails a test, which
 * is what stops the changelog quietly falling behind the thing it describes.
 *
 *   node scripts/catalog-snapshot.mjs             write one for today, if anything changed
 *   node scripts/catalog-snapshot.mjs --check     say whether one is needed, and exit 1 if so
 */

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const DIR = here('../packages/changelog/snapshots');

const result = await build({
  configFile: false,
  logLevel: 'error',
  build: {
    write: false,
    ssr: true,
    lib: { entry: here('./refresh/snapshot-entry.ts'), formats: ['es'], fileName: 'snapshot' },
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});

const output = Array.isArray(result) ? result[0].output : result.output;
const code = output.find((chunk) => chunk.type === 'chunk').code;
const changelog = await import(
  `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
);

const today = new Date().toISOString().slice(0, 10);
const taken = changelog.serialiseSnapshot(changelog.takeSnapshot(today));

const existing = readdirSync(DIR)
  .filter((name) => name.endsWith('.json'))
  .sort();
const latest = existing[existing.length - 1];

// The date is the only thing that always differs, so it is ignored when asking "did anything move".
const withoutDate = (text) => text.replace(/"takenOn": "\d{4}-\d{2}-\d{2}"/, '"takenOn": ""');

if (latest !== undefined) {
  const previous = readFileSync(`${DIR}/${latest}`, 'utf8');
  if (withoutDate(previous) === withoutDate(taken)) {
    // The index is cheap and idempotent, so it is kept in step even on a no-op run.
    writeIndex();
    console.log(`nothing changed since ${latest.replace('.json', '')}`);
    process.exit(0);
  }
}

if (process.argv.includes('--check')) {
  console.error(
    `The catalogue has changed since ${latest ?? 'the beginning'}. Run node scripts/catalog-snapshot.mjs and commit the file it writes.`,
  );
  process.exit(1);
}

writeFileSync(`${DIR}/${today}.json`, taken);
writeIndex();
console.log(`wrote packages/changelog/snapshots/${today}.json`);

/*
 * A generated index, so the website can import the history without reading the filesystem. It is
 * committed with the snapshot it names, and a test fails if the two disagree.
 */
function writeIndex() {
  const files = readdirSync(DIR)
    .filter((name) => name.endsWith('.json'))
    .sort();
  const lines = [
    '/*',
    ' * Generated by scripts/catalog-snapshot.mjs. Do not edit.',
    ' *',
    ' * The history is imported rather than read off disk, because the website is a static export',
    ' * and has no filesystem at run time. Oldest first.',
    ' */',
    "import type { Snapshot } from '../src/snapshot';",
    '',
    ...files.map((name, i) => `import s${String(i)} from './${name}';`),
    '',
    `export const HISTORY: Snapshot[] = [${files.map((_, i) => `s${String(i)}`).join(', ')}] as Snapshot[];`,
    '',
  ];
  writeFileSync(`${DIR}/index.ts`, lines.join('\n'));
}
